    let notRun = ["Actual drawable presentation and file-selection UI", "US, Palette and compressed color support", "ICC and physical monitor color matching"]
}

private enum CheckError: Error { case assertion(String) }

/// Safe categories only. Raw error reasons are inspected for path leakage but
/// never appear in a report, stderr, or an assertion message.
private enum ErrorCategory: String, Sendable {
    case resourceLimit, invalidArgument, unsupported, decodeFailed
    case sessionClosed, busy, invalidContract, copyFailed, renderingFailed, other

    static func classify(_ error: any Error) -> ErrorCategory {
        switch error {
        case ViewerPixelError.resourceLimit: .resourceLimit
        case ViewerPixelError.invalidArgument: .invalidArgument
        case ViewerPixelError.unsupported: .unsupported
        case ViewerPixelError.decodeFailed: .decodeFailed
        case ViewerPixelError.sessionClosed: .sessionClosed
        case ViewerPixelError.busy: .busy
        case ViewerPixelError.invalidContract: .invalidContract
        case ViewerPixelError.copyFailed: .copyFailed
        case is RenderingError: .renderingFailed
        default: .other
        }
    }

    static func reason(_ error: any Error) -> String? {
        switch error {
        case ViewerPixelError.resourceLimit(let reason), ViewerPixelError.invalidArgument(let reason),
             ViewerPixelError.unsupported(let reason), ViewerPixelError.decodeFailed(let reason),
             ViewerPixelError.invalidContract(let reason): reason
        default: nil
        }
    }
}

private struct FixtureEntry: Decodable, Sendable {
    let id: String
    let bytes: UInt64
    let sha256: String
    let rows: UInt32
    let columns: UInt32
    let rgba8: [UInt8]?
}
private struct FixtureManifest: Decodable, Sendable {
    let revision: Int
    let syntheticOnly: Bool
    let fixtures: [FixtureEntry]
    enum CodingKeys: String, CodingKey {
        case revision, fixtures
        case syntheticOnly = "synthetic_only"
    }
}
private struct FileDigest: Sendable, Equatable { let bytes: UInt64; let sha256: String }

private struct ColorFixture: Sendable {
    let id: String
    let width: UInt32
    let rgba: [UInt8]?
    let doubledLinearRow: [UInt8]?
    let tolerance: Int
    let rejection: ErrorCategory?
    var expected: String { rejection?.rawValue ?? "literal_rgba_and_descriptor" }
}

/// Expectations are independent literals, not generated by the decoder or
/// loaded as the pixel oracle from the manifest. Only these synthetic IDs can
/// be emitted by this executable.
private enum Fixtures {
    static let rgb: [UInt8] = [
        255,0,0,255, 0,255,0,255, 0,0,255,255,
        0,0,0,255, 255,255,255,255, 17,34,51,255
