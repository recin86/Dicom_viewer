#!/usr/bin/env python3
"""P0 whole/frame decode peak-RSS observation, independent lossless formula."""
import argparse
import hashlib
import json
import re
import subprocess
import time
from pathlib import Path

import numpy as np
import pydicom
from pydicom.dataset import FileDataset, FileMetaDataset
from pydicom.uid import ExplicitVRLittleEndian, RLELossless, MultiFrameGrayscaleWordSecondaryCaptureImageStorage


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--binary', type=Path, required=True)
    ap.add_argument('--work-dir', type=Path, required=True)
    ap.add_argument('--report', type=Path, required=True)
    args = ap.parse_args()
    work = args.work_dir
    work.mkdir(parents=True, exist_ok=True)
    rows = cols = 512
    count = 32
    yy, xx = np.indices((rows, cols), dtype=np.uint16)
    pixels = np.stack([(xx + 2 * yy + 17 * n) % 4096 for n in range(count)])
    meta = FileMetaDataset()
    meta.TransferSyntaxUID = ExplicitVRLittleEndian
    meta.MediaStorageSOPClassUID = MultiFrameGrayscaleWordSecondaryCaptureImageStorage
    meta.MediaStorageSOPInstanceUID = '1.2.826.0.1.3680043.10.999.910'
    meta.ImplementationClassUID = '1.2.826.0.1.3680043.10.999.1'
    ds = FileDataset(None, {}, file_meta=meta, preamble=b'\0' * 128)
    ds.SOPClassUID = meta.MediaStorageSOPClassUID
    ds.SOPInstanceUID = meta.MediaStorageSOPInstanceUID
    ds.Modality = 'OT'
    ds.Rows, ds.Columns, ds.NumberOfFrames = rows, cols, count
    ds.SamplesPerPixel = 1
    ds.PhotometricInterpretation = 'MONOCHROME2'
    ds.BitsAllocated, ds.BitsStored, ds.HighBit, ds.PixelRepresentation = 16, 12, 11, 0
    ds.PixelData = pixels.astype('<u2').tobytes()
    ds.compress(RLELossless, encoding_plugin='pydicom', generate_instance_uid=False)
    source = work / 'memory-rle-32.dcm'
    ds.save_as(source, enforce_file_format=True)
    reread = pydicom.dcmread(source)
    if not np.array_equal(reread.pixel_array, pixels):
        raise ValueError('Generated fixture does not match independent formula')
    before = hashlib.sha256(source.read_bytes()).hexdigest()
    results = []
    for mode in ['whole', 'frame']:
        for repeat in range(3):
            prefix = work / f'{mode}-{repeat}'
            cmd = ['/usr/bin/time', '-l', str(args.binary), str(source), str(prefix)]
            if mode == 'frame':
                cmd += ['--frame', str(count - 1)]
            started = time.perf_counter()
            proc = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
            elapsed = time.perf_counter() - started
            # Keep raw time diagnostics local: they may contain executable paths.
            (work / f'{mode}-{repeat}-time.txt').write_text(proc.stderr)
            info = json.loads(proc.stdout)
            rss_match = re.search(r'(\d+)\s+maximum resident set size', proc.stderr)
            if mode == 'whole':
                values = np.fromfile(str(prefix) + '.stored.f64le', dtype='<f8')
                correct = np.array_equal(values, pixels.ravel())
            else:
                values = np.fromfile(str(prefix) + f'.frame-{count-1}.f64le', dtype='<f8')
                correct = np.array_equal(values, pixels[-1].ravel())
            after = hashlib.sha256(source.read_bytes()).hexdigest()
            ok = proc.returncode == 0 and info.get('status') == 'ok' and correct and after == before
            frame_info = info.get('frame_results', [{}])[0] if mode == 'frame' else info
            results.append({'mode': mode, 'repeat': repeat, 'status': 'pass' if ok else 'fail',
                            'max_rss_bytes': int(rss_match.group(1)) if rss_match else None,
                            'elapsed_seconds_including_parse_conversion_and_file_io': elapsed,
                            'decoded_bytes': frame_info.get('decoded_bytes'), 'decode_ms': frame_info.get('decode_ms'),
                            'all_pixels_equal': bool(correct), 'source_hash_unchanged': after == before})
            del values
            for path in work.glob(prefix.name + '.*'):
                path.unlink()
    report = {'fixture_id': 'synthetic-memory-rle-32', 'sha256': before,
              'source': 'project-generated by bench_memory.py, independent (x+2*y+17*f)%4096 formula',
              'redistribution': 'synthetic generated source; no patient data',
              'frames': count, 'rows': rows, 'cols': cols, 'transfer_syntax': str(RLELossless),
              'decoded_native_bytes': int(pixels.nbytes), 'single_native_frame_bytes': int(pixels[0].nbytes),
              'scope': 'process peak RSS includes object parsing, f64 vectors, outputs and codec; no app/GPU performance claim',
              'results': results}
    args.report.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({'fixture_id': report['fixture_id'], 'results': results}, indent=2))
    return 0 if all(r['status'] == 'pass' for r in results) else 1


if __name__ == '__main__':
    raise SystemExit(main())
