        accepted("sc-rgb-planar-implicit.dcm", rgb, linear: rgbLinearRow),
        accepted("sc-rgb-interleaved-be.dcm", rgb, linear: rgbLinearRow),
        rejected("us-rgb-interleaved.dcm"),
        accepted("sc-ybr-full-interleaved.dcm", ybr, linear: ybrLinearRow, tolerance: 1),
        accepted("sc-ybr-full-planar.dcm", ybr, linear: ybrLinearRow, tolerance: 1),
        rejected("defer-us-ybr-full-planar.dcm"),
        rejected("defer-us-ybr-full-interleaved.dcm"),
        accepted("sc-ybr-full-422.dcm", ybr422, linear: ybr422LinearRow, width: 4, tolerance: 1),
        rejected("defer-us-ybr-full-422.dcm", width: 4),
